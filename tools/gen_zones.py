#!/usr/bin/env python3
"""Generate src/zones.rs from the system IANA tzdata.

Each TZif file's footer carries the zone's POSIX TZ rule string (the
rule set currently in force). We embed (zone name -> rule) for every
canonical zone, deduplicating rule strings. Re-run when tzdata updates
and bump TZDATA_VERSION. The data is a factual compilation from the
IANA Time Zone Database (public domain).
"""
import os
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
OUT = sys.argv[2] if len(sys.argv) > 2 else "src/zones.rs"

SKIP_PREFIXES = ("posix/", "right/")
SKIP_FILES = {"localtime", "posixrules", "tzdata.zi", "zone.tab", "zone1979.tab",
              "leapseconds", "leap-seconds.list", "README", "METADATA"}


def footer_posix(path):
    with open(path, "rb") as f:
        data = f.read()
    if not data.startswith(b"TZif"):
        return None
    parts = data.rsplit(b"\n", 2)
    if len(parts) < 3:
        return ""
    return parts[-2].decode("ascii", "replace").strip()


zones = {}
for dirpath, _dirs, files in os.walk(ROOT):
    for name in files:
        full = os.path.join(dirpath, name)
        rel = os.path.relpath(full, ROOT)
        if rel in SKIP_FILES or rel.startswith(SKIP_PREFIXES):
            continue
        posix = footer_posix(full)
        if posix is None:
            continue
        if posix == "":
            # Fixed zones whose file carries no rule string.
            if rel in ("UTC", "Etc/UTC", "Etc/Universal", "Universal", "Zulu", "Etc/Zulu"):
                posix = "UTC0"
            elif rel in ("GMT", "Etc/GMT", "GMT0", "Etc/GMT0", "Greenwich", "Etc/Greenwich"):
                posix = "GMT0"
            else:
                print(f"WARNING: no rule for {rel}, skipped", file=sys.stderr)
                continue
        zones[rel] = posix

rules = []
rule_idx = {}
for z in sorted(zones):
    r = zones[z]
    if r not in rule_idx:
        rule_idx[r] = len(rules)
        rules.append(r)

version = "unknown"
zi = os.path.join(ROOT, "tzdata.zi")
if os.path.exists(zi):
    with open(zi) as f:
        for line in f:
            if line.startswith("# version"):
                version = line.split()[-1]
                break

with open(OUT, "w") as f:
    f.write("// GENERATED by tools/gen_zones.py from IANA tzdata — do not edit by hand.\n")
    f.write(f'pub const TZDATA_VERSION: &str = "{version}";\n\n')
    f.write("/// (zone name, index into RULES), sorted by name.\n")
    f.write("pub static ZONES: &[(&str, u16)] = &[\n")
    for z in sorted(zones):
        esc = zones[z].replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'    ("{z}", {rule_idx[zones[z]]}), // {esc}\n')
    f.write("];\n\n")
    f.write("/// Deduplicated POSIX TZ rule strings.\n")
    f.write("pub static RULES: &[&str] = &[\n")
    for r in rules:
        esc = r.replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'    "{esc}",\n')
    f.write("];\n")

print(f"{len(zones)} zones, {len(rules)} distinct rules, tzdata {version} -> {OUT}")
